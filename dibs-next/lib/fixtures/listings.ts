// Asking prices are sellers' prices, not business values.
const ph = (icon: string) => [`ph:${icon}:0`, `ph:${icon}:1`, `ph:${icon}:2`];
const ago = (hours: number) => new Date(Date.parse('2026-10-08T19:00:00Z') - hours * 3600_000).toISOString();

const L = (
  n: number,
  sellerId: string,
  source: ListingSource,
  title: string,
  dollars: number,
  condition: Condition,
  category: Category,
  housingFit: HousingFit,
  icon: string,
  hoursAgo: number,
  description: string,
  status: ListingStatus = 'active',
): Listing => ({
  id: `l${String(n).padStart(2, '0')}`,
  campusId: findUser(sellerId).campusId,
  sellerId,
  source,
  title,
  description,
  priceCents: Math.round(dollars * 100),
  condition,
  category,
  housingFit,
  photos: ph(icon),
  status,
  createdAt: ago(hoursAgo),
});

